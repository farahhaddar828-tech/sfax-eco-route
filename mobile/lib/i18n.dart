/// Look up a translated string for the currently selected language.
String t(String key) {
  final lang = Settings.instance.language;
  return _strings[lang]?[key] ?? _strings['fr']?[key] ?? key;
}

/// Look up a translated string and fill its `{placeholders}`.
String tp(String key, Map<String, String> args) {
  var s = t(key);
  args.forEach((k, v) => s = s.replaceAll('{$k}', v));
  return s;
}

/// Localised name of a report category: `catLabel('waste')`.
String catLabel(String key) => t('cat.$key');

/// Localised name of a priority band: `priorityText('critical')`.
String priorityText(String label) =>
    t('priority.${const ['critical', 'high', 'medium', 'low'].contains(label) ? label : 'low'}');

